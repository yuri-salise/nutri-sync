"""
Generate documentation that must match the code (D1 chapter 4 / appendix B, D3).

Writes, relative to the repository root:
  docs/03-api/openapi.yaml                           OpenAPI 3 document of the running app
  docs/01-system-documentation/generated/erd.md      Mermaid ERD from the SQLAlchemy models
  docs/01-system-documentation/generated/data-dictionary.md
  docs/01-system-documentation/generated/endpoints.md

Usage (from backend/, with SECRET_KEY and DATABASE_URL set as for the tests):
    python -m app.scripts.export_docs
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Dict, List

import yaml

BASE_DIR = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(BASE_DIR))

from app.db import models, routine_models, social_models  # noqa: E402,F401  (register tables)
from app.db.base import Base  # noqa: E402
from app.main import app  # noqa: E402

REPO_ROOT = BASE_DIR.parent
GENERATED = REPO_ROOT / "docs" / "01-system-documentation" / "generated"
NOTE = "<!-- Generated by backend/app/scripts/export_docs.py. Do not edit by hand. -->\n"


def _type_name(column) -> str:
    try:
        return str(column.type)
    except Exception:
        return type(column.type).__name__.upper()


def _mermaid_type(column) -> str:
    return _type_name(column).split("(")[0].replace(" ", "_") or "TEXT"


def erd() -> str:
    lines = ["erDiagram"]
    tables = Base.metadata.sorted_tables
    for table in tables:
        for fk in table.foreign_keys:
            parent = fk.column.table.name
            lines.append(f'    {parent} ||--o{{ {table.name} : "{fk.parent.name}"')
    for table in tables:
        lines.append(f"    {table.name} {{")
        for col in table.columns:
            marks = []
            if col.primary_key:
                marks.append("PK")
            if col.foreign_keys:
                marks.append("FK")
            lines.append(f"        {_mermaid_type(col)} {col.name} {' '.join(marks)}".rstrip())
        lines.append("    }")
    return NOTE + "# Entity-relationship diagram\n\n```mermaid\n" + "\n".join(lines) + "\n```\n"


def data_dictionary() -> str:
    out = [NOTE, "# Data dictionary\n"]
    for table in Base.metadata.sorted_tables:
        out.append(f"## {table.name}\n")
        out.append("| Column | Type | Null | Key | Default | Constraints |")
        out.append("| :--- | :--- | :---: | :--- | :--- | :--- |")
        for col in table.columns:
            key = "PK" if col.primary_key else ""
            if col.foreign_keys:
                refs = ", ".join(f"FK -> {fk.target_fullname}" for fk in col.foreign_keys)
                key = f"{key} {refs}".strip()
            default = ""
            if col.default is not None and getattr(col.default, "arg", None) is not None:
                arg = col.default.arg
                default = getattr(arg, "__name__", str(arg))
            constraints = []
            if col.unique:
                constraints.append("UNIQUE")
            if col.index:
                constraints.append("INDEX")
            out.append(
                f"| `{col.name}` | {_type_name(col)} | {'yes' if col.nullable else 'no'} "
                f"| {key} | {default} | {', '.join(constraints)} |"
            )
        checks = [c.sqltext for c in table.constraints if c.__class__.__name__ == "CheckConstraint"]
        for check in checks:
            out.append(f"\nCheck: `{check}`")
        out.append("")
    return "\n".join(out)


def endpoints(spec: dict) -> str:
    rows: List[str] = []
    by_tag: Dict[str, List[str]] = {}
    for path, item in sorted(spec["paths"].items()):
        for method, op in item.items():
            if method not in {"get", "post", "put", "patch", "delete"}:
                continue
            secured = (
                "yes" if op.get("security") or "Authorization" in str(op.get("parameters")) else ""
            )
            tag = (op.get("tags") or ["other"])[0]
            codes = ", ".join(sorted(op.get("responses", {}).keys()))
            by_tag.setdefault(tag, []).append(
                f"| {method.upper()} | `{path}` | {op.get('summary', '')} | {codes} | {secured} |"
            )
    rows.append(NOTE)
    rows.append("# Endpoint list\n")
    for tag, lines in sorted(by_tag.items()):
        rows.append(f"## {tag}\n")
        rows.append("| Method | Path | Summary | Responses | Auth header |")
        rows.append("| :--- | :--- | :--- | :--- | :---: |")
        rows.extend(lines)
        rows.append("")
    return "\n".join(rows)


def main() -> None:
    spec = app.openapi()
    api_dir = REPO_ROOT / "docs" / "03-api"
    api_dir.mkdir(parents=True, exist_ok=True)
    (api_dir / "openapi.yaml").write_text(
        yaml.safe_dump(spec, sort_keys=False, allow_unicode=True), encoding="utf-8", newline="\n"
    )
    GENERATED.mkdir(parents=True, exist_ok=True)
    (GENERATED / "erd.md").write_text(erd(), encoding="utf-8", newline="\n")
    diagrams = REPO_ROOT / "docs" / "diagrams"
    diagrams.mkdir(parents=True, exist_ok=True)
    mermaid = erd().split("```mermaid\n", 1)[1].rsplit("```", 1)[0]
    (diagrams / "database_erd.mmd").write_text(mermaid, encoding="utf-8", newline="\n")
    (GENERATED / "data-dictionary.md").write_text(data_dictionary(), encoding="utf-8", newline="\n")
    (GENERATED / "endpoints.md").write_text(endpoints(spec), encoding="utf-8", newline="\n")
    paths = sum(
        1
        for item in spec["paths"].values()
        for m in item
        if m in {"get", "post", "put", "patch", "delete"}
    )
    print(
        f"Wrote openapi.yaml ({paths} operations), "
        f"{len(Base.metadata.tables)} tables in the ERD and data dictionary."
    )


if __name__ == "__main__":
    main()
